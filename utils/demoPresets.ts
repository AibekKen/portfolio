const PLACEHOLDER = /X{2,3} XXX/g

const escapeRegExp = (value: string) => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')

// Prices typed over the XX XXX placeholders, or null once the chat was edited beyond them
export const extractPrices = (nicheId: string, lang: DemoLang, msgs: DemoMessage[], handoff: string): string[] | null => {
  const preset = demoNiches.find((niche) => niche.id === nicheId)?.content[lang]

  if (!preset || preset.handoff !== handoff || preset.msgs.length !== msgs.length) {
    return null
  }

  const prices: string[] = []

  for (const [index, template] of preset.msgs.entries()) {
    const message = msgs[index]!
    const pattern = new RegExp(`^${template.text.split(PLACEHOLDER).map(escapeRegExp).join('(.+?)')}$`)
    const match = template.from === message.from ? message.text.match(pattern) : null

    if (!match) {
      return null
    }

    prices.push(...match.slice(1))
  }

  return prices
}

const expandShortDemo = (short: ShortDemo): DemoData | null => {
  const preset = demoNiches.find((niche) => niche.id === short.n)?.content[short.l]

  if (!preset) {
    return null
  }

  let next = 0
  const msgs = preset.msgs.map((message) => ({
    ...message,
    text: message.text.replace(PLACEHOLDER, () => short.p[next++] ?? 'XX XXX'),
  }))

  return { v: 1, lang: short.l, biz: short.b, channel: 'WhatsApp', time: short.t, msgs, handoff: preset.handoff }
}

// Reads either link format back into a full chat
export const resolveDemo = (hash: string): DemoData | null => {
  const data = decodeDemo(hash)
  return data?.v === 2 ? expandShortDemo(data) : data
}

export type OutreachKind = 'slow' | 'none' | 'warm'

export type OutreachParams = {
  biz: string
  link: string
  time: string
  hours: number
  name: string
}

const ruHours = (n: number) => {
  const mod10 = n % 10
  const mod100 = n % 100
  if (mod10 === 1 && mod100 !== 11) return `${n} час`
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return `${n} часа`
  return `${n} часов`
}

const signature = (name: string) => (name.trim() ? `${name.trim()}, kenzcore AI Studio` : 'kenzcore AI Studio')

